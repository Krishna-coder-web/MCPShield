    def analyze(self, prompt: str):
        
        prompt_lower = normalize(prompt)

        score = 0
        matched_patterns = []

        for pattern, value in self.attack_patterns.items():

            if pattern in prompt_lower:
                score += value
                matched_patterns.append(pattern)

        score = min(score, 100)
        best_category = "NONE"
        semantic_score = 0

        for category, examples in self.categories.items():

            current_score = similarity(
                prompt_lower,
                examples
            )

            if current_score > semantic_score:
                semantic_score = current_score
                best_category = category

        if semantic_score > 0.75:
            score += 30
        elif semantic_score > 0.65:
            score += 15
        score = min(score, 100)

        threat = score > 0
        
        if score >= 70:
            severity = "HIGH"
        elif score >= 40:
            severity = "MEDIUM"
        elif score > 0:
            severity = "LOW"
        else:
            severity = "NONE"

        return {
            "threat": threat,
            "threat_type": best_category if threat else "NONE",
            "score": score,
            "matched_patterns": matched_patterns,
            "severity": severity,
            "semantic_score": round(semantic_score, 3),
        }